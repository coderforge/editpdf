"""Builds backend/dist/function/: exactly what the Cloud Builder Function
deploys (Terraform zips the directory).

    manifest.json        how the platform runs it: Python, main.py, function_handler
    main.py              the entry file, defining function_handler(event, context)
    editpdf/             the service, with resources/ (the OpenAPI document, the
                         version of the Terms and Conditions) and static/ (the
                         web interface, frontend/dist)
    pypdf/               its one dependency, pure Python

Functions run in a sandboxed WebAssembly runtime (Pyodide, for Python), so
everything in the package is pure Python and is read through importlib, never
from paths: the runtime may import the package straight from its zip.

Build the interface first (npm run build, in frontend/), or pass --api-only
for a function that serves the API alone.

    python backend/scripts/build_function.py [--api-only]
"""

from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
from pathlib import Path

BACKEND = Path(__file__).resolve().parents[1]
REPOSITORY = BACKEND.parent
OUT = BACKEND / "dist" / "function"

HANDLER = "function_handler"

ENTRY_POINT = f'''"""Cloud Builder Function entry file: the runtime calls {HANDLER}(event, context).
Generated by backend/scripts/build_function.py: edit editpdf/function.py instead."""

from editpdf.function import handler as {HANDLER}

__all__ = ["{HANDLER}"]
'''

# What the platform reads to run the package (coderforge_function): the
# bundle describes itself, so Terraform names no handler or runtime.
MANIFEST = {"type": "python", "main": "main.py", "handler": HANDLER}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--api-only", action="store_true", help="leave the web interface out")
    args = parser.parse_args()

    interface = REPOSITORY / "frontend" / "dist"
    if not args.api_only and not (interface / "index.html").is_file():
        sys.exit("frontend/dist is missing: build the interface first (npm run build), or pass --api-only")

    shutil.rmtree(OUT, ignore_errors=True)
    OUT.mkdir(parents=True)

    # The dependencies, as pure-Python wheels only: the function must not
    # depend on the machine it was built on.
    subprocess.run(
        [
            sys.executable,
            "-m",
            "pip",
            "install",
            "--quiet",
            "--no-compile",
            "--only-binary=:all:",
            "--target",
            str(OUT),
            "--requirement",
            str(BACKEND / "requirements.txt"),
        ],
        check=True,
    )
    shutil.rmtree(OUT / "bin", ignore_errors=True)

    shutil.copytree(BACKEND / "src" / "editpdf", OUT / "editpdf", ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
    resources = OUT / "editpdf" / "resources"
    resources.mkdir()
    shutil.copy2(REPOSITORY / "openapi" / "editpdf-v1.yaml", resources / "openapi.yaml")
    shutil.copy2(REPOSITORY / "legal" / "VERSION", resources / "TERMS_VERSION")
    shutil.copy2(REPOSITORY / "LICENSE", OUT / "LICENSE")
    (OUT / "main.py").write_text(ENTRY_POINT, encoding="utf-8")
    (OUT / "manifest.json").write_text(json.dumps(MANIFEST, indent=2) + "\n", encoding="utf-8")

    if not args.api_only:
        shutil.copytree(interface, OUT / "editpdf" / "static")

    files = [path for path in OUT.rglob("*") if path.is_file()]
    size = sum(path.stat().st_size for path in files)
    print(f"{OUT.relative_to(REPOSITORY)}: {len(files)} files, {size / 1024 / 1024:.1f} MiB (main.py, {HANDLER})")


if __name__ == "__main__":
    main()
